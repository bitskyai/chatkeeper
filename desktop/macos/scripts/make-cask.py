#!/usr/bin/env python3
"""Writes the Homebrew cask for the menu-bar app (chatkeeper-app).

GoReleaser OSS cannot build or reference DMGs, so the desktop release job
renders the cask from the DMG it just built and pushes it to the tap.

    make-cask.py --version 0.1.0 --dmg dist/ChatKeeper-0.1.0.dmg --out Casks/chatkeeper-app.rb [--unsigned] [--auto-updates]
"""
import argparse
import hashlib
import pathlib
import re

REPO = "bitskyai/chatkeeper"
BUNDLE_ID = "ai.bitsky.chatkeeper"


def render(version: str, sha256: str, unsigned: bool, auto_updates: bool) -> str:
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?", version):
        raise SystemExit(f"invalid version: {version!r}")
    if not re.fullmatch(r"[0-9a-f]{64}", sha256):
        raise SystemExit("invalid sha256")
    lines = [
        "# Generated by desktop/macos/scripts/make-cask.py. Do not edit.",
        'cask "chatkeeper-app" do',
        f'  version "{version}"',
        f'  sha256 "{sha256}"',
        "",
        f'  url "https://github.com/{REPO}/releases/download/v#{{version}}/ChatKeeper-#{{version}}.dmg"',
        '  name "ChatKeeper"',
        '  desc "Menu-bar app that keeps selected chat threads in a local archive"',
        f'  homepage "https://github.com/{REPO}"',
        "",
        "  livecheck do",
        "    url :url",
        "    strategy :github_latest",
        "  end",
        "",
    ]
    if auto_updates:
        lines.append("  auto_updates true")
    lines += [
        '  depends_on macos: ">= :ventura"',
        "",
        '  app "ChatKeeper.app"',
        "",
    ]
    if unsigned:
        lines += [
            "  # v0.1 is not yet signed with a Developer ID: clear the quarantine",
            "  # attribute so Gatekeeper does not block the first launch.",
            "  postflight do",
            '    system_command "/usr/bin/xattr",',
            '                   args: ["-dr", "com.apple.quarantine", "#{appdir}/ChatKeeper.app"],',
            "                   sudo: false",
            "  end",
            "",
        ]
    lines += [
        f'  uninstall quit:       "{BUNDLE_ID}",',
        '            login_item: "ChatKeeper"',
        "",
        "  # Archives in ~/Library/Application Support/chatkeeper are user data and",
        "  # are intentionally never removed by zap.",
        "  zap trash: [",
        '    "~/Library/Caches/' + BUNDLE_ID + '",',
        '    "~/Library/HTTPStorages/' + BUNDLE_ID + '",',
        '    "~/Library/Logs/ChatKeeper",',
        '    "~/Library/Preferences/' + BUNDLE_ID + '.plist",',
        "  ]",
        "",
        "  caveats <<~EOS",
        "    ChatKeeper lives in the menu bar. Your archives are stored in",
        "      ~/Library/Application Support/chatkeeper",
        "    and are kept when the app is uninstalled.",
    ]
    if unsigned:
        lines += [
            "",
            "    This build is not signed with an Apple Developer ID. Homebrew removed",
            "    the quarantine attribute; if macOS still blocks it, run:",
            "      xattr -dr com.apple.quarantine /Applications/ChatKeeper.app",
        ]
    lines += ["  EOS", "end", ""]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--version", required=True)
    p.add_argument("--dmg", required=True, type=pathlib.Path)
    p.add_argument("--out", required=True, type=pathlib.Path)
    p.add_argument("--unsigned", action="store_true")
    p.add_argument("--auto-updates", action="store_true")
    a = p.parse_args()
    digest = hashlib.sha256(a.dmg.read_bytes()).hexdigest()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(a.version.removeprefix("v"), digest, a.unsigned, a.auto_updates))
    print(f"wrote {a.out} ({digest})")


if __name__ == "__main__":
    main()
