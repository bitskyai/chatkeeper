#!/usr/bin/env python3
"""Writes the Homebrew formula for the CLI/server (chatkeeper) from a
GoReleaser dist/SHA256SUMS.

GoReleaser deprecated `brews` in favour of `homebrew_casks`, but a cask cannot
declare a `brew services` daemon, so the release workflow renders the formula
itself and pushes it to the tap.

    make-formula.py --version 0.1.0 --sums dist/SHA256SUMS --out Formula/chatkeeper.rb
"""
import argparse
import pathlib
import re

REPO = "bitskyai/chatkeeper"
TARGETS = [  # (homebrew block, goos, goarch)
    ("on_macos", "on_arm", "darwin", "arm64"),
    ("on_macos", "on_intel", "darwin", "amd64"),
    ("on_linux", "on_arm", "linux", "arm64"),
    ("on_linux", "on_intel", "linux", "amd64"),
]


def archive(version: str, goos: str, goarch: str) -> str:
    return f"chatkeeper_{version}_{goos}_{goarch}.tar.gz"


def render(version: str, sums: dict[str, str]) -> str:
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?", version):
        raise SystemExit(f"invalid version: {version!r}")
    lines = [
        "# Generated by scripts/make-formula.py. Do not edit.",
        "class Chatkeeper < Formula",
        '  desc "Keep selected chat threads in a local, searchable, read-only archive"',
        f'  homepage "https://github.com/{REPO}"',
        f'  version "{version}"',
        '  license "MIT"',
        "",
    ]
    for os_block in ("on_macos", "on_linux"):
        lines.append(f"  {os_block} do")
        for block, cpu, goos, goarch in TARGETS:
            if block != os_block:
                continue
            name = archive(version, goos, goarch)
            digest = sums.get(name)
            if not digest or not re.fullmatch(r"[0-9a-f]{64}", digest):
                raise SystemExit(f"missing sha256 for {name}")
            lines += [
                f"    {cpu} do",
                f'      url "https://github.com/{REPO}/releases/download/v#{{version}}/{name.replace(version, "#{version}")}"',
                f'      sha256 "{digest}"',
                "    end",
            ]
        lines.append("  end")
    lines += [
        "",
        "  def install",
        '    bin.install "chatkeeper"',
        "  end",
        "",
        "  service do",
        '    run [opt_bin/"chatkeeper", "run", "--no-browser"]',
        "    keep_alive successful_exit: false",
        "    # stdout carries the per-launch login token; never write it to the",
        "    # shared Homebrew log directory. stderr has no secrets.",
        '    error_log_path var/"log/chatkeeper.log"',
        "  end",
        "",
        "  def caveats",
        "    <<~EOS",
        "      Start ChatKeeper and open its browser UI:",
        "        chatkeeper run",
        "      Or keep it running in the background (loopback only):",
        "        brew services start chatkeeper",
        "      then run `chatkeeper run` again to open the browser UI of the running instance.",
        "      The menu-bar app is a cask: brew install --cask bitskyai/tap/chatkeeper-app",
        "    EOS",
        "  end",
        "",
        "  test do",
        '    assert_match "chatkeeper", shell_output("#{bin}/chatkeeper version")',
        "  end",
        "end",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--version", required=True)
    p.add_argument("--sums", required=True, type=pathlib.Path)
    p.add_argument("--out", required=True, type=pathlib.Path)
    a = p.parse_args()
    sums = {}
    for line in a.sums.read_text().splitlines():
        parts = line.split()
        if len(parts) == 2:
            sums[parts[1].lstrip("*")] = parts[0]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render(a.version.removeprefix("v"), sums))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
